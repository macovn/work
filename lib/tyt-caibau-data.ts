export function inferDepartmentFromStaff(staff: {
  vtvlCode?: string;
  qualification?: string;
  concurrentRole?: string;
  fullName?: string;
}): string {
  const code = staff.vtvlCode || "";
  const role = (staff.concurrentRole || "").toLowerCase();
  const qual = (staff.qualification || "").toLowerCase();

  // 1. Dược
  if (code.includes(".04.") || qual.includes("dược") || role.includes("dược") || role.includes("kho thuốc")) {
    return "Dược";
  }

  // 2. Dân số
  if (code.includes(".10.") || role.includes("dân số") || qual.includes("dân số")) {
    return "Dân số";
  }

  // 3. Văn phòng
  if (
    code.includes(".13.") ||
    code.includes(".12.") ||
    code.includes(".11.") ||
    code.includes(".09.") ||
    role.includes("giám đốc") ||
    role.includes("kế toán") ||
    role.includes("văn phòng") ||
    role.includes("cntt")
  ) {
    return "Văn phòng";
  }

  // 4. Phòng bệnh
  if (
    code.includes(".05.") ||
    role.includes("dịch tễ") ||
    role.includes("tiêm chủng") ||
    role.includes("an toàn thực phẩm") ||
    role.includes("môi trường") ||
    role.includes("y tế trường học") ||
    qual.includes("ytcc")
  ) {
    return "Phòng bệnh";
  }

  // 5. Khám bệnh (Bác sĩ, Y sĩ, Điều dưỡng KCB, Hộ sinh)
  return "Khám bệnh";
}

